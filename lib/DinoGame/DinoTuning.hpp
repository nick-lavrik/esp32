#pragma once

#include <stdint.h>

// Налаштування гри. Усе, що стосується РОЗМІРУ, задано у частках (зросту діно
// чи ширини екрана), усе, що стосується ЧАСУ - в секундах. Жодних «пікселів за
// кадр»: кадрова частота тут плаває від 10 до 200 fps залежно від плати й від
// того, чим саме зайнятий loop(), тому прив'язка до кадру зробила б гру різною
// на кожній платі.
struct DinoTuning {
  // Стрибок
  float jumpApexBodies = 1.75f;  // апекс = 1.75 зросту діно (як в оригіналі);
                                 // рендер додатково обмежує його вільним місцем
  float jumpRiseSec = 0.32f;     // час підйому до апексу
  float holdExtraSec = 0.18f;  // скільки ще діє полегшена гравітація, поки тримають
  float holdGravityScale = 0.45f;  // множник гравітації під час утримання
  float cutRiseScale = 0.45f;  // на відпусканні швидкість підйому зрізається до цієї частки

  // Швидкість світу (у ширинах екрана за секунду)
  float startSpeedRatio = 0.55f;
  float maxSpeedRatio = 1.60f;
  float speedGainPerSec = 0.030f;

  // Проміжок між перешкодами - у СЕКУНДАХ ходу, не в пікселях. Це і є гарантія
  // прохідності: на будь-якій швидкості гравець має однаковий час на реакцію.
  float gapMinSec = 0.68f;
  float gapMaxSec = 1.55f;

  float hitboxShrink = 0.16f;    // усадка хітбоксів (див. DinoRect::shrunk)
  float scorePerScreen = 40.0f;  // очок за пройдену ширину екрана
  float runStepRatio = 0.028f;   // крок анімації бігу, у ширинах екрана

  // Найбільший крок часу, який модель погодиться інтегрувати за раз.
  // loop() ділиться з mqtt.loop()/WiFi, і там реально бувають стопи на сотні
  // мілісекунд (у main.cpp навіть стоїть warn на це). Без обмеження один такий
  // стоп телепортував би кактус крізь діно - і гравець отримав би game over
  // за подію, якої не бачив.
  float maxStepSec = 0.10f;

  uint16_t restartLockMs = 400;  // «мертвий час» після game over
};
