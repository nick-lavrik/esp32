#pragma once

#include <stdint.h>

// Стан динозавра. y відлічується ВГОРУ від землі: 0 - стоїть на землі,
// додатне - у повітрі. Так формули стрибка не залежать від того, де саме
// на екрані проходить лінія горизонту.
struct DinoPlayer {
  float y = 0.0f;   // висота над землею, px
  float vy = 0.0f;  // вертикальна швидкість, px/s (додатна - вгору)

  bool onGround() const { return y <= 0.0f; }
};
