#include <cstdint>
#include <functional>

// USB Mass Storage: плата віддає SD картку хосту як звичайний блочний
// пристрій (/dev/sdX).
//
// НАВІЩО: на картці деградувала flash-пам'ять, і мета - зняти образ, щоб
// потім записати його на нову картку. Власний HTTP-канал для цього годиться
// погано: він упирається в TCP-вікно lwIP (~450 KiB/s), залежить від WiFi і
// вимагає власного інструменту копіювання замість перевірених. Через USB MSC
// хост бачить картку як диск, і працюють штатні ddrescue/e2fsck/partclone -
// з їхніми картами прогресу, повторними спробами та resume.
//
// ТІЛЬКИ ЧИТАННЯ, і це забезпечено на двох рівнях: isWritable(false) змушує
// ОС змонтувати пристрій read-only, а обробник запису однаково відмовляє.
// Для картки, що вмирає, будь-який запис (наприклад, відтворення журналу
// ext4 при монтуванні) може бути останнім.
//
// Вимагає ARDUINO_USB_MODE=0 (режим OTG): при ARDUINO_USB_MODE=1 USB
// працює як апаратний CDC і TinyUSB, а з ним і MSC, недоступний.
// Читач секторів: (перший LBA, скільки, куди) -> успіх. Постачає main.cpp,
// щоб MSC не залежав від того, як картка підключена - по SPI чи по SDMMC.
// Це не абстракція про запас: на цій деградованій картці SDMMC-режим
// заводить її в стан помилки після серії CRC-збоїв (лікується лише зняттям
// живлення), тоді як SPI-драйвер читає ті самі сектори годинами. А оскільки
// вузьке місце - USB (752 KiB/s), швидкість самого інтерфейсу тут не важить.
using SdMscSectorReader = std::function<bool(uint32_t lba, uint32_t count, uint8_t *out)>;

bool sdMassStorageBegin(SdMscSectorReader reader, uint32_t totalSectors);
void sdMassStorageEnd();
bool sdMassStorageActive();

// true (і скидає прапорець), якщо накопичилась серія помилок читання і картку
// варто перемонтувати.
//
// ВИКЛИКАТИ ЛИШЕ З ГОЛОВНОГО ЦИКЛУ. Перша версія перемонтовувала картку прямо
// в USB-callback, тобто з таску TinyUSB, і це валило систему: плата
// перезавантажувалась посеред знімання образу, а хост бачив лише
// "No medium found". Драйвер картки має підніматися з того потоку, що ним
// володіє, тому модуль лише повідомляє про потребу, а вирішує викличний код.
bool sdMassStorageNeedsRecovery();

// Скинути буфер читання наперед - обов'язково після перемонтування картки,
// інакше хост отримає дані, прочитані до перемонтування.
void sdMassStorageInvalidatePrefetch();

// Друкує стан і статистику (скільки секторів віддано, скільки збоїв).
void sdMassStoragePrintStatus();

#endif  // BOARD_ESP32_S3_LCD147
