#pragma once

// Куди ще дублювати КОЖЕН рядок логу - незалежно від таска, з якого він
// прийшов. Один sink на весь пристрій.
//
// Навіщо окремо від LogCaptureRegistry. Той навмисно per-task: захоплення
// виводу команди мусить брати рядки лише з таска, де команда виконується, щоб
// у відповідь не сипались рядки "mqtt-net" та "ecoflow-rest" (див. коментар у
// LogCaptureRegistry.hpp). Для дзеркала консолі вимога протилежна - потрібні
// саме ВСІ таски, бо сенс у тому, щоб віддалено бачити те саме, що в
// serial-моніторі. Тому це не режим реєстру, а окремий глобальний вказівник:
// два механізми працюють одночасно й незалежно (рядок може піти і у відповідь
// на команду, і в дзеркало).
//
// Sink отримує вже сформований рядок: з префіксом "[I][tag    ] ", після
// фільтра LogLevelManager і після UTF-8-безпечного обрізання - тобто рівно те,
// що йде в консоль. Викликається з будь-якого таска, тому реалізація write()
// має бути неблокуюча (див. lib/ConsoleMqtt).
//
// Працює лише з SerialLogger-бекендом (-D USE_SERIAL_LOGGER, стоїть у
// [common] для всіх плат); EspLogger пише в esp_log і повз цей механізм.
//
// Платформо-специфічних гілок тут немає (на відміну від решти файлів
// lib/Logger): std::atomic<Print*> лягає і на ESP32, і на ESP8266.

#include <Print.h>

#include <atomic>

class LogMirror {
public:
  // nullptr - вимкнути дзеркало. Ставиться один раз при старті.
  static void set(Print* sink);

  // Sink або nullptr. Читається на КОЖЕН рядок логу, тому навмисно без
  // мьютекса - relaxed-читання одного вказівника (те саме рішення, що в
  // LogCaptureRegistry::current()).
  static Print* current();

private:
  static std::atomic<Print*> _sink;
};
