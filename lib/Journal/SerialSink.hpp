#pragma once

// Приймач журналу, що друкує записи у фізичний Serial.
//
// Сенс усього рефактора видно саме тут: serial більше не привілейований вихід
// у надрах логера, а ОДИН ІЗ читачів журналу - такий самий, як MQTT-дзеркало
// чи веб-консоль. Формат рядка ("[I][tag    ] текст") належить йому, а не
// логеру: інші приймачі вільні віддавати те саме інакше.
//
// Пише під тим самим rwlock, що й раніше, і з тим самим таймаутом. Якщо порт
// зайнятий - повертає false, і журнал спробує той самий запис наступною
// помпою: рядок не губиться і порядок не ламається.

#include <cstddef>

#include <Journal.hpp>

class SerialSink {
 public:
  // Підписує себе в журнал. Кликати ПІСЛЯ Serial.begin().
  static void attach(Journal& journal = Journal::instance());

  // Сирий вивід у консоль, ПОВЗ журнал. Єдиний легальний виняток із правила
  // "усе через логер", і причина конкретна: машинні дампи ('bg-dump' друкує
  // C-заголовок на 385 КБ, який './esp bg-save' зберігає у файл). Префікс
  // "[I][tag    ] " зіпсував би результат, а 24 тисячі рядків через кільце на
  // 32 записи - це 24 тисячі публікацій, помп і пробуджень таска.
  //
  // Пише під ТИМ САМИМ замком, що й приймач, тому чужий рядок не може
  // розрізати наш посеред тексту. І, на відміну від голого Serial.print(),
  // ЧЕКАЄ місця в TX: при setTxTimeoutMs(0) print() мовчки відкидає зайве
  // (див. коментар у deliver()), а для дампу, який потім компілюється,
  // пропущені байти - зіпсований файл.
  // false - шматок НЕ вийшов цілим (не вдалось узяти замок або хост не читає
  // TX). Викликач мусить це помітити: для дампу, який потім компілюється,
  // тихий пропуск гірший за помилку.
  static bool writeRaw(const char* text, size_t length = 0);

 private:
  static bool deliver(const JournalEntry& entry);
};
