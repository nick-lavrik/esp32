#pragma once

// Один запис журналу - структурований, а не готовий рядок.
//
// Це головна відмінність від того, що було до рефактора: раніше
// SerialLogger::log() формував "[I][tag    ] текст\n" у найнижчій точці, і всі
// читачі (serial, MQTT-дзеркало, веб-консоль, відповідь на команду) отримували
// вже склеєний рядок. Тег існував лише як 7 символів усередині тексту, тому
// фільтрувати за ним можна було хіба регексом.
//
// Тепер рівень, тег і текст живуть окремо, а префікс додає КОЖЕН приймач сам:
// serial лишає звичний вигляд, веб може віддати JSON, екран - обрізати тег
// заради ширини.
//
// ЧАС ЖИТТЯ tag і task. Обидва зберігаються як const char*, БЕЗ копії - запис
// має лишатись дешевим (publish() це один memcpy під мьютексом). Тому
// контракт: рядок мусить пережити запис у кільці. Для тегів це виконується
// само - у проєкті всі вони рядкові літерали, і ILogger уже сьогодні тримає
// `const char* _tag` з тим самим припущенням. Для task - pcTaskGetName()
// повертає вказівник на TCB, тобто живе, поки живий таск.

#include <cstddef>
#include <cstdint>

// Рівень логування. Живе тут, а не в ILogger.hpp, бо Journal - нижчий шар:
// про нього знає і логер, і кожен приймач, а про логер приймачі знати не
// зобов'язані.
enum class LogLevel { Error = 0, Warn = 1, Info = 2, Debug = 3, Verbose = 4 };

// Скільки байтів тексту вміщає запис. 160 - та сама межа, що була в
// PrintQueue::kLineSize, щоб обрізання довгих рядків лишилось таким самим до
// байта (див. критерій приймання етапу 1 у docs/journal_plan.md).
#ifndef JOURNAL_TEXT_SIZE
#define JOURNAL_TEXT_SIZE 160
#endif

struct JournalEntry {
  static constexpr size_t kTextSize = JOURNAL_TEXT_SIZE;

  uint32_t seq = 0;      // наскрізний номер: глобальний порядок і курсори
  uint32_t timeMs = 0;   // millis() у момент publish()
  const char* tag = "";  // ключ маршрутизації, ієрархічний ("mqtt.send")
  const char* task = "";  // ім'я таска-джерела; фільтр для відповіді на команду
  LogLevel level = LogLevel::Info;
  uint16_t length = 0;  // довжина text без '\0'
  char text[kTextSize] = {};  // БЕЗ префікса і БЕЗ '\n'
};

// "E" / "W" / "I" / "D" / "V" - для префікса рядка.
const char* journalLevelName(LogLevel level);

// "error" / "warn" / "info" / "debug" / "verbose" - для команди 'journal',
// де однобуквене позначення нічого не пояснює.
const char* journalLevelFullName(LogLevel level);

// Розбирає те, що ввели в консолі: повне ім'я, літеру або цифру 0..4
// (регістр неважливий). false - не рівень.
bool journalLevelParse(const char* text, LogLevel& out);

// Формує префікс "[I][tag    ] " у buf і повертає його довжину (без '\0'),
// або 0, якщо не влазить.
//
// Одна функція на весь проєкт навмисно: її кличе і SerialSink (щоб надрукувати
// рядок), і SerialLogger (щоб порахувати, скільки місця лишилось під текст).
// Дві копії розійшлись би, і обрізання довгих рядків поїхало б на кілька
// байтів - тихо й непомітно.
size_t journalFormatPrefix(LogLevel level, const char* tag, char* buf, size_t size);

// Складає ЦІЛИЙ рядок "[I][tag    ] текст" (без '\n') у buf і повертає його
// довжину без '\0'; 0 - не влазить навіть префікс.
//
// Одна функція на всіх споживачів: serial, MQTT-дзеркало, веб-консоль і
// 'journal tail' показують той самий рядок, і розходитись їм нема з чого.
// Хто хоче перенос - дописує його сам: у serial він потрібен, в MQTT ні
// (там один запис = одне повідомлення).
size_t journalFormatLine(const JournalEntry& entry, char* buf, size_t size);
