#pragma once

#include <stdint.h>

// Єдина точка входу для роботи з IMU (акселерометр/гіроскоп) - за тим самим
// принципом, що й TouchController (lib/TouchScreen/TouchController.h):
//
// Клас лише ОГОЛОШЕНО тут (компілюється завжди, коли BOARD_HAS_IMU=1).
// РЕАЛІЗАЦІЯ - у конкретній платі, підключається через build_src_filter:
//   env:esp32-c6 -> src-esp32-c6/ImuController.cpp (QMI8658A, I2C)
//
// ЧОМУ САМЕ ТАК, а не "-D HAS_QMI8658": різні IMU (QMI8658, MPU6050, BMI270,
// LSM6DS3) мають ЗОВСІМ різні набори регістрів, масштаби і порядок осей -
// спільного «як у всіх» протоколу не існує. Тому тут розділено два рівні:
//   BOARD_HAS_IMU=1 - фіча ("на платі є IMU"), нею оперує спільний main.cpp;
//   IMU_QMI8658     - конкретний чип, ним оперує лише реалізація плати.
// Рівно та сама пара, що вже є для тача: BOARD_HAS_TOUCHSCREEN + драйвер у
// src-<board>/. Додати іншу плату з іншим IMU = додати ще один .cpp, не
// чіпаючи ні main.cpp, ні цей заголовок.
class ImuController {
 public:
  // Орієнтація плати В ПЛОЩИНІ ЕКРАНА - тобто де опинився ВЕРХНІЙ рядок
  // зображення, а НЕ куди дивиться сам екран.
  //
  // Розрізняти це принципово: поворот навколо нормалі до екрана (верх стає
  // низом) і перевертання екраном донизу - різні рухи, і дають їх різні осі
  // акселерометра. Для цієї плати верх/низ видно по осі X, а не Z
  // (Z майже не змінюється при такому повороті) - див. IMU_UP_AXIS.
  enum class Orientation : uint8_t {
    Unknown,  // ще не визначено (немає стабільних показань)
    TopUp,    // верх зображення вгорі
    TopDown,  // плату повернуто на 180 градусів, верх опинився внизу
  };

  // Ініціалізація чипа. Повертає false, якщо IMU не відгукнувся на шині -
  // спільний код у такому разі просто працює далі без нього.
  // I2C-шину (Wire.begin) ініціалізує ВИКЛИКАЧ: вона спільна з тачем,
  // тому піднімається один раз у main.cpp::setupI2C().
  static bool setup();

  // Опитування сенсора. Викликати щоцикл з loop(); усередині стоїть власний
  // інтервал опитування, тому зайвих I2C-транзакцій не буде.
  static void update();

  // Поточна (вже стабілізована) орієнтація.
  static Orientation orientation();

  // Останні прочитані прискорення по всіх трьох осях, у g - для діагностики
  // ("imu" в консолі). Три осі, а не лише одна: яка з них вертикальна,
  // залежить від того, як чип розпаяний на конкретній платі, і вгадати це
  // наперед не можна (на ESP32-C6-Touch-LCD-1.47 це виявилась НЕ Z).
  static float accelX();
  static float accelY();
  static float accelZ();

  // Вісь, за якою визначається переворот, і її поточне значення в g
  // (уже з урахуванням IMU_UP_AXIS_SIGN). Задається прапорцями
  // IMU_UP_AXIS (0=X, 1=Y, 2=Z) і IMU_UP_AXIS_SIGN (+1/-1).
  static float upAxisValue();
  static const char* upAxisName();

  static const char* orientationName(Orientation o);
};
