#pragma once

#include <WifiConnection.hpp>

// Прошитий перелік WiFi-мереж плати - "заводський" запис, а не робоча
// конфігурація: netSupervisor.seedConnections() додає звідси лише ті SSID,
// яких у списку ще немає (див. setupNetworkSupervisor() у main.cpp). Робоче
// сховище - NVS, там профілі й редагуються командою 'net'.
//
// Чому таблиця, а не сама лише пара з secrets.ini: мереж у реальності більше
// однієї (роутер, 5 ГГц, хотспот з телефона), і вони відрізняються пріоритетом.
// Опис однієї макросом, а решти вручну через 'net' означав би, що після чистої
// прошивки плата знає половину того, що знає розробник.
//
// Обидві форми співіснують, і ролі в них різні:
//   * іменовані рядки - постійні мережі, однакові для всіх плат; вони в git;
//   * WIFI_SSID_SEED/WIFI_PASSWORD_SEED - змінна мережа "тут і зараз"
//     (secrets.ini, поза git): підміняється без правки коду, і кожна плата
//     може мати свою. Пріоритет 0 саме тому - це запасний варіант, який не
//     має відтісняти постійні мережі.
//
// Чому в src/, а не поруч із seedConnections() у lib/NetworkSupervisor: тут
// креденшели конкретного пристрою, бібліотека лишається переносною (той самий
// поділ, що в src/Ecoflow/EcoflowDeviceRegistry).
//
// УВАГА: "Asus " - з ПРОБІЛОМ на кінці, це справжнє ім'я мережі, а не одрук.
// Пробіл виживає в ефірі й у роутері, але тихо гине скрізь, де рядок проходить
// через trim: саме через нього в netcli::splitArgs() є режим лапок ('net
// connection add ssid "Asus "'), інакше профіль з консолі не ввести. Прибрати
// пробіл тут - зламати підключення, а не "причесати таблицю".
//
// Паролі беруться ВИКЛЮЧНО з макросів: secrets.ini у .gitignore, а цей файл -
// ні. SSID тут відкриті свідомо: вони й так в ефірі.

// Порожній пароль = відкрита мережа, тож fallback безпечний лише як заглушка
// для збірки без ключа в secrets.ini - підключення по ньому все одно не буде.
#ifndef WIFI5_PASSWORD
#define WIFI5_PASSWORD ""
#endif

inline constexpr WifiNetworkInfo kWifiNetworks[] = {
    {.ssid = "Asus ", .password = WIFI5_PASSWORD, .priority = 100},
    {.ssid = "5G.nick.lavrik", .password = WIFI5_PASSWORD, .priority = 100},
    // Нова постійна мережа - рядок тут плюс ключ у secrets.ini і -D у
    // platformio.ini:
    // {.ssid = "Pixel", .password = WIFI_PASSWORD_HOTSPOT, .priority = 50},

    // Seed - ОСТАННІМ рядком, і це не косметика. seedConnections() пропускає
    // SSID, який у списку вже є, тож із дублем (у secrets.ini лежать
    // закоментовані "Asus " і "5G.nick.lavrik" - їх легко розкоментувати)
    // виграє ТОЙ, ХТО ЙДЕ РАНІШЕ. Стояв би seed першим - мережа мовчки дістала
    // б пріоритет 0 замість 100 і пароль з іншого ключа.
    {.ssid = WIFI_SSID_SEED, .password = WIFI_PASSWORD_SEED, .priority = 0},
};
